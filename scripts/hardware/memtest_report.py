#!/usr/bin/env python3
"""Parse MemTest86 HTML reports (V11.x, UTF-16 or UTF-8) into a compact comparison table.

Why: the PassMark report is the only artifact that survives a run — the on-screen summary drops
detail, and the vendor reads the HTML. Reading it by eye is how a 66%-complete run gets quoted as
a result. This pulls the fields the campaign actually decides on, and refuses to guess.

Usage:
    python3 memtest_report.py REPORT.html [REPORT2.html ...]
    python3 memtest_report.py --json REPORT.html
    python3 memtest_report.py --dir /Volumes/MEMTEST   # every *.html at the USB root
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

TESTS_PER_PASS = 12  # MemTest86 V11.7 default test set (0..10 + 13)
CELL = re.compile(r"</t[dh]>", re.I)
ROW = re.compile(r"</tr>", re.I)
TAG = re.compile(r"<[^>]+>")
WS = re.compile(r"[ \xa0\u00a0]+")


def decode(path: str) -> str:
    raw = open(path, "rb").read()
    for enc in ("utf-16", "utf-16-le", "utf-8-sig", "utf-8", "latin-1"):
        try:
            text = raw.decode(enc)
        except (UnicodeDecodeError, LookupError):
            continue
        if "MemTest86" in text or "Result" in text:
            return text
    return raw.decode("latin-1", "replace")


def cells(path: str) -> list[str]:
    text = decode(path)
    text = CELL.sub("\t", text)
    text = ROW.sub("\n", text)
    text = TAG.sub("", text)
    out = []
    for line in text.split("\n"):
        # A tab is a cell boundary, not whitespace: "Test Start Time\t2026-10-18 19:15:23"
        # must become two entries or the value is lost.
        for part in line.split("\t"):
            part = WS.sub(" ", part).strip()
            if part:
                out.append(part)
    return out


def parse(path: str) -> dict:
    lines = cells(path)
    flat = "\n".join(lines)

    def after(label: str) -> str | None:
        """Value is the next line after an exact label line."""
        try:
            i = lines.index(label)
        except ValueError:
            return None
        return lines[i + 1] if i + 1 < len(lines) else None

    def find(pattern: str) -> str | None:
        m = re.search(pattern, flat, re.M)
        return m.group(1).strip() if m else None

    r: dict = {"file": os.path.basename(path), "path": os.path.abspath(path)}
    r["report_date"] = after("Report Date")
    r["version"] = after("Generated by")
    r["result"] = after("Result")
    # BIOS version: the first "Version" after the "BIOS" label (the header has its own "Version").
    try:
        i = lines.index("BIOS")
        j = lines.index("Version", i)
        r["bios"] = lines[j + 1] if j + 1 < len(lines) else None
    except ValueError:
        r["bios"] = None
    r["mem_config"] = after("RAM Configuration")
    r["mem_installed"] = after("Memory")
    r["modules"] = after("Number of RAM modules")
    r["start"] = after("Test Start Time")
    r["elapsed"] = after("Elapsed Time")
    r["cpu_temp"] = after("CPU Temperature Min/Max/Ave")

    # Slot population: "DIMM 0 / 32GB ..." then "DIMM 0 / Empty" — record each occurrence.
    slots = []
    for i, line in enumerate(lines):
        if re.fullmatch(r"DIMM \d+", line):
            slots.append({"slot": line, "value": lines[i + 1] if i + 1 < len(lines) else ""})
    r["slots"] = slots

    done = after("# Tests Completed")
    passed = after("# Tests Passed")
    r["tests_completed"] = done
    r["tests_passed"] = passed
    m = re.match(r"(\d+)/(\d+)", done or "")
    if m:
        completed = int(m.group(1))
        r["passes_derived"] = completed // TESTS_PER_PASS
        r["tests_into_pass"] = completed % TESTS_PER_PASS

    r["lowest_err_addr"] = after("Lowest Error Address")
    r["highest_err_addr"] = after("Highest Error Address")
    mask = after("Bits in Error Mask")
    r["bit_mask_hex"] = mask
    if mask:
        try:
            v = int(mask, 16)
            r["error_bits"] = [i for i in range(v.bit_length()) if v >> i & 1]
        except ValueError:
            r["error_bits"] = None
    r["bits_in_error"] = after("Bits in Error")
    r["max_contiguous"] = after("Max Contiguous Errors")

    # Per-test table: name, passed fraction, error count.
    tests = []
    for i, line in enumerate(lines):
        m = re.match(r"^Test (\d+) \[(.*)\]$", line)
        if not m:
            continue
        frac = lines[i + 1] if i + 1 < len(lines) else ""
        errs = lines[i + 2] if i + 2 < len(lines) else ""
        tests.append({
            "test": int(m.group(1)),
            "name": m.group(2),
            "passed": frac,
            "errors": int(errs) if errs.isdigit() else errs or None,
        })
    r["tests"] = tests

    errs = re.findall(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d - \[[^\]]+\].*)$", flat, re.M)
    r["last_errors"] = errs[-10:]

    def total_errors():
        vals = [t["errors"] for t in tests if isinstance(t["errors"], int)]
        return sum(vals) if vals else None

    r["error_total"] = total_errors()
    return r


def fmt(x) -> str:
    return "—" if x in (None, "", []) else str(x)


def show(r: dict) -> None:
    print(f"\n{r['file']}")
    print(f"  result        {fmt(r['result'])}  ({fmt(r['version']).split('(')[0].strip()})")
    print(f"  report date   {fmt(r['report_date'])}   started {fmt(r['start'])}   elapsed {fmt(r['elapsed'])}")
    print(f"  modules       {fmt(r['modules'])}   memory {fmt(r['mem_installed'])}   {fmt(r['mem_config'])}")
    slots = ", ".join(f"{s['slot']}={s['value'][:28]}" for s in r["slots"]) or "—"
    print(f"  slots         {slots}")
    print(f"  tests         completed {fmt(r['tests_completed'])}, passed {fmt(r['tests_passed'])}")
    if "passes_derived" in r:
        print(f"  passes        {r['passes_derived']} complete + {r['tests_into_pass']} test(s) into the next")
    if r["error_total"] is not None:
        print(f"  errors        {r['error_total']} total"
              + (f", bits {r['error_bits']} (mask {r['bit_mask_hex']})" if r.get("error_bits") else ""))
        if r.get("lowest_err_addr"):
            print(f"  error range   {r['lowest_err_addr']} .. {r['highest_err_addr']}")
        bad = [t for t in r["tests"] if isinstance(t["errors"], int) and t["errors"] > 0]
        for t in bad:
            print(f"    test {t['test']:>2} [{t['name']}]: {t['errors']} errors ({t['passed']})")
    if r["last_errors"]:
        print("  last 10:")
        for e in r["last_errors"]:
            print(f"    {e}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("reports", nargs="*")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--dir", help="scan a directory (e.g. the USB mount) for *.html reports")
    a = ap.parse_args()

    paths = list(a.reports)
    if a.dir:
        paths += sorted(glob.glob(os.path.join(a.dir, "*.html")))
    if not paths:
        ap.error("no report files given")

    results = []
    for p in paths:
        try:
            results.append(parse(p))
        except Exception as e:  # a malformed report must not hide the others
            print(f"!! {p}: {e}", file=sys.stderr)

    if a.json:
        print(json.dumps(results, indent=2))
        return 0

    for r in results:
        show(r)

    if len(results) > 1:
        print("\n" + "=" * 78)
        print(f"{'report date':>19} {'result':>8} {'elapsed':>9} {'tests':>8} {'errors':>7}  bits  module layout")
        for r in results:
            bits = ",".join(map(str, r.get("error_bits") or [])) or "-"
            lay = ",".join(s["value"].split()[0] if s["value"] else "?" for s in r["slots"])
            print(f"{fmt(r['report_date']):>19} {fmt(r['result']):>8} {fmt(r['elapsed']):>9} "
                  f"{fmt(r['tests_completed']):>8} {fmt(r['error_total']):>7}  {bits:>5} {lay}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
